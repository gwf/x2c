#!/bin/sh
# Writes src/linked-meta.x, the shipped `meta` code compiled into the
# compiler, from the sources that define it. Each bodied `meta` definition
# of lib/meta.x and of every `.xmacro` a shipped compiler or runtime source
# imports is copied without its `meta` marker, so its tokens, and therefore
# its definition hash, match the source. A lib/meta.x builder with a
# run-time form is bound to the runtime's own definition instead: one that
# is not static and reaches no compiler operation. The file is rewritten
# only when its text changes.
set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
out=${1:-$root/src/linked-meta.x}
cd "$root"

# The imported `.xmacro` files that hold a bodied `meta` definition, in name
# order, which is also the order they are copied in.
imported=$(grep -ho '\$(import "[^"]*\.xmacro")' src/*.x lib/*.x \
    lib/*.xmacro src/*.xmacro |
  sed 's/.*"\(.*\)")/\1/; s|.*/||' | sort -u)
sources=lib/meta.x
for name in $imported; do
  for dir in lib src; do
    file=$dir/$name
    [ -f "$file" ] && grep -q '^meta ' "$file" && sources="$sources $file"
  done
done

tmp="$out.$$"
trap 'rm -f "$tmp"' EXIT
awk '
function scan(line,    i, ch, n) {
  n = length(line)
  for (i = 1; i <= n; i++) {
    ch = substr(line, i, 1)
    if (incomment) {
      if (ch == "*" && substr(line, i + 1, 1) == "/") { incomment = 0; i++ }
      continue
    }
    if (quote != "") {
      if (ch == "\\") i++
      else if (ch == quote) quote = ""
      continue
    }
    if (ch == "/" && substr(line, i + 1, 1) == "*") { incomment = 1; i++ }
    else if (ch == "/" && substr(line, i + 1, 1) == "/") break
    else if (ch == "\"" || ch == "\x27") quote = ch
    else if (ch == "(" || ch == "{" || ch == "[") depth++
    else if (ch == ")" || ch == "}" || ch == "]") depth--
  }
}
function finish(    name, text) {
  text = def
  if (text !~ /=>/ && text !~ /\{/) { prototypes[++nproto] = defname; return }
  if (text !~ /\)[ \t\n]*(=>|\{)/) return
  ndef++
  names[ndef] = defname
  bodies[ndef] = (defdoc == "" ? "" : defdoc "\n") text
  statics[ndef] = (header ~ /^meta static /)
  files[ndef] = FILENAME
}
FNR == 1 { capturing = 0; indoc = 0; doc = "" }
capturing {
  def = def "\n" $0
  scan($0)
  if (depth == 0 && $0 ~ /[;}][ \t]*$/) { capturing = 0; finish() }
  next
}
# A doc comment directly above a definition travels with its copy.
indoc { doc = doc "\n" $0; if ($0 ~ /\*\//) indoc = 0; next }
/^\/\*\*/ { doc = $0; if ($0 !~ /\*\//) indoc = 1; next }
/^meta / {
  header = $0
  defdoc = doc
  defname = $0
  sub(/\(.*/, "", defname)
  sub(/.*[^A-Za-z0-9_]/, "", defname)
  def = substr($0, 6)
  depth = 0; quote = ""; incomment = 0
  scan($0)
  if (depth == 0 && $0 ~ /[;}][ \t]*$/) finish()
  else capturing = 1
}
{ doc = "" }
function calls(text, name) {
  return text ~ ("(^|[^A-Za-z0-9_])" name "[ \t]*\\(")
}
END {
  # A static definition has no run-time symbol, and one that reaches a
  # compiler operation has no run-time form, so both are copied.
  for (i = 1; i <= ndef; i++) copied[i] = statics[i]
  for (i = 1; i <= ndef; i++)
    for (p = 1; p <= nproto; p++)
      if (calls(bodies[i], prototypes[p])) copied[i] = 1
  do {
    changed = 0
    for (i = 1; i <= ndef; i++) {
      if (copied[i]) continue
      for (j = 1; j <= ndef; j++)
        if (copied[j] && calls(bodies[i], names[j])) {
          copied[i] = 1; changed = 1; break
        }
    }
  } while (changed)

  print "/*  linked-meta.x -- shipped `meta` code compiled into the compiler"
  print ""
  print "    Generated by tools/gen-linked-meta.sh; do not edit. Each bodied"
  print "    `meta` definition of lib/meta.x and of the imported `.xmacro`"
  print "    files appears here without its `meta` marker, so it runs as"
  print "    native code instead of through the Lisp lowering."
  print "    `Compiler.bind_linked_meta` binds an imported definition to its"
  print "    copy only when the two texts hash the same, so a compiler built"
  print "    before a `.xmacro` edit stages the edited definition. The"
  print "    lib/meta.x builders with a run-time form bind to the runtime\047s"
  print "    own definitions and have no copy here."
  print "*/"
  print ""
  print "#pragma once"
  print ""
  print "#include \"x2c.x\""
  print "#include \"meta.x\""
  last = ""
  for (i = 1; i <= ndef; i++) {
    if (!copied[i]) continue
    if (files[i] != last) {
      print ""
      print "/* --- " files[i] " " substr("--------------------------------------------------------------------------", 1, 68 - length(files[i])) " */"
      last = files[i]
    }
    print ""
    print bodies[i]
  }
  print ""
  print "/* --- the linked inventory " substr("--------------------------------------------------", 1, 48) " */"
  print ""
  print "macro Statement $linked.row(Expr $rows, Expr $name, Expr $function) {"
  print "  $rows[$name] = Func.new("
  print "    $function, $(_x2c.literal.list (_x2c.function.native-type $function)));"
  print "}"
  print ""
  print "/** Returns the linked copies, and the runtime builders, by name. */"
  print "Map linked_meta_targets(void) {"
  print "  Map rows = {};"
  for (i = 1; i <= ndef; i++)
    if (copied[i]) print "  $linked.row(rows, \"" names[i] "\", " names[i] ");"
  for (i = 1; i <= ndef; i++)
    if (!copied[i]) print "  $linked.row(rows, \"" names[i] "\", " names[i] ");"
  print "  return rows;"
  print "}"
  print ""
  print "/** Returns the hash of each linked copy\047s definition text by name. */"
  print "Map linked_meta_hashes(void) => $x2c_meta_definition_hashes();"
}
' $sources > "$tmp"
if [ -e "$out" ] && cmp -s "$tmp" "$out"; then
  rm -f "$tmp"
else
  mv "$tmp" "$out"
fi
trap - EXIT
