#!/usr/bin/env python3
"""Generate the current x2c module and public-function catalog."""

from __future__ import annotations

import argparse
import difflib
import pathlib
import sys
import textwrap
from dataclasses import dataclass

from x2c_source import module_summary
from x2c_symbols import load as load_symbols, definitions_with_symbols


ROOT = pathlib.Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "agents" / "x2c-module-catalog.md"
SOURCE_DIRS = (ROOT / "src", ROOT / "lib")
SKIP_MODULES = {ROOT / "lib" / "x2c.x"}


@dataclass(frozen=True)
class Module:
    path: pathlib.Path
    summary: str
    functions: tuple[str, ...]


def discover_modules() -> tuple[Module, ...]:
    modules: list[Module] = []
    symbols = load_symbols()
    for directory in SOURCE_DIRS:
        for path in sorted(directory.glob("*.x")):
            if path in SKIP_MODULES:
                continue
            text = path.read_text(encoding="utf-8")
            modules.append(Module(
                path=path.relative_to(ROOT),
                summary=module_summary(text, path),
                functions=tuple(item.name for item in
                    definitions_with_symbols(path, symbols)),
            ))
    return tuple(modules)


def wrapped_names(names: tuple[str, ...]) -> list[str]:
    if not names:
        return ["None. This module has no non-static function definitions."]
    rendered = ", ".join(f"`{name}`" for name in names)
    return textwrap.wrap(
        rendered,
        width=79,
        initial_indent="",
        subsequent_indent="",
        break_long_words=False,
        break_on_hyphens=False,
    )


def render() -> str:
    modules = discover_modules()
    compiler = tuple(m for m in modules if m.path.parts[0] == "src")
    runtime = tuple(m for m in modules if m.path.parts[0] == "lib")
    lines = [
        "# X2C Module and API Catalog",
        "",
        "> Generated by `python3 tools/gen-module-catalog.py --write` from",
        "> current `src/*.x` and `lib/*.x` sources. Do not edit by hand.",
        "",
        "The catalog lists every authoritative source module and every",
        "non-static function definition discovered in source order. It does",
        "not claim that partial runtime contracts are complete; consult",
        "`agents/x2c-philosophy.md` for contract status.",
        "",
        f"- Compiler modules: {len(compiler)}",
        f"- Runtime modules: {len(runtime)}",
        "- Generated runtime aggregator: `lib/x2c.x` (`lib/Makefile` owns it)",
        "",
    ]
    for title, group in (("Compiler modules", compiler),
                         ("Runtime modules", runtime)):
        lines.extend((f"## {title}", ""))
        for module in group:
            source_path = module.path.as_posix()
            lines.extend((
                f"### [{source_path}](../{source_path})",
                "",
                module.summary,
                "",
                "Public functions:",
                "",
            ))
            lines.extend(wrapped_names(module.functions))
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def check(expected: str) -> int:
    actual = OUTPUT.read_text(encoding="ascii") if OUTPUT.exists() else ""
    if actual == expected:
        print("module catalog is current")
        return 0
    diff = difflib.unified_diff(
        actual.splitlines(),
        expected.splitlines(),
        fromfile=str(OUTPUT.relative_to(ROOT)),
        tofile="generated catalog",
        lineterm="",
    )
    print("\n".join(diff), file=sys.stderr)
    print("run 'make doc-generate' and review the catalog diff", file=sys.stderr)
    return 1


def main() -> int:
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = render()
    if args.write:
        OUTPUT.write_text(output, encoding="ascii")
        print(f"wrote {OUTPUT.relative_to(ROOT)}")
        return 0
    if args.check:
        return check(output)
    sys.stdout.write(output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
