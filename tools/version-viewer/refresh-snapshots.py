#!/usr/bin/env python3
"""Generate browser snapshots from a manifest of canonical source files."""

import argparse
import json
from pathlib import Path


def main():
    root = Path(__file__).resolve().parent
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("manifest", nargs="?", type=Path,
                        default=root.parent.parent / "examples/c2x2c/versions.json")
    args = parser.parse_args()
    manifest = args.manifest.resolve()
    data = json.loads(manifest.read_text(encoding="utf-8"))
    versions = []
    for version in data["versions"]:
        source = manifest.parent / version["path"]
        text = source.read_text(encoding="utf-8")
        for extra in version.get("append", []):
            text += "\n" + (manifest.parent / extra).read_text(encoding="utf-8")
        versions.append({"label": version["label"],
                         "filename": version["path"],
                         "source": text})
    data["versions"] = versions
    encoded = json.dumps(data, indent=2, ensure_ascii=True)
    script = ("/* Generated by refresh-snapshots.py; edit canonical sources. */\n"
              "window.TUTORIAL_SNAPSHOTS = " + encoded + ";\n")
    (root / "snapshots.json").write_text(encoded + "\n", encoding="utf-8")
    (root / "snapshots.js").write_text(script, encoding="utf-8")
    for version in versions:
        print(f'{version["filename"]}: {len(version["source"].splitlines())} lines')


if __name__ == "__main__":
    main()
