#!/usr/bin/env python3
"""Assemble the shared Lisp environment using the existing x2c lowering."""

import argparse
import os
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--compiler", default=str(ROOT / "builds/0/x2c"))
    args = parser.parse_args()
    compiler = Path(args.compiler).resolve()
    with tempfile.TemporaryDirectory(prefix="x2c-init-") as directory:
        work = Path(directory)
        subprocess.run(
            [str(compiler), "translate", str(ROOT / "etc/init.x"),
             "--out-dir", str(work)], cwd=work,
            env=os.environ | {"X2C_HOME": str(ROOT)}, check=True,
        )
        text = ("// Generated by tools/gen-lisp-init.py; edit init-core.xlisp "
                "and init.x.\n\n")
        prefix, suffix = (ROOT / "etc/init-core.xlisp").read_text().split(
            "// Generated algorithms belong here.", 1
        )
        text += "\n".join(
            line for line in prefix.splitlines()
            if line.strip() and not line.lstrip().startswith("//")
        ) + "\n"
        text += "\n// Generated x2c algorithms.\n\n"
        text += "\n".join(
            line.rstrip() for line in
            (work / "init-generated.xlisp").read_text().splitlines()
        ) + "\n"
        text += "\n" + suffix.strip() + "\n"
    output = ROOT / "etc/init.xlisp"
    if output.read_text() != text:
        output.write_text(text)
        print("refreshed etc/init.xlisp")


if __name__ == "__main__":
    main()
