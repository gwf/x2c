#!/usr/bin/env python3
"""Assemble shared and compiler-only Lisp using the existing x2c lowering."""

import argparse
import os
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--compiler", default=str(ROOT / "builds/0/x2c"))
    args = parser.parse_args()
    compiler = Path(args.compiler).resolve()
    generate(compiler, "init", "init-core", "init")
    generate(compiler, "builtin-macros", "builtin-core", "builtins")


def generate(compiler, name, core, emitted):
    with tempfile.TemporaryDirectory(prefix="x2c-lisp-") as directory:
        work = Path(directory)
        subprocess.run(
            [str(compiler), "translate", str(ROOT / f"etc/{name}.x"),
             "--out-dir", str(work)], cwd=work,
            env=os.environ | {"X2C_HOME": str(ROOT)}, check=True,
        )
        text = (f"// Generated by tools/gen-lisp-init.py; edit {core}.xlisp "
                f"and {name}.x.\n\n")
        prefix, suffix = (ROOT / f"etc/{core}.xlisp").read_text().split(
            "// Generated algorithms belong here.", 1
        )
        text += "\n".join(
            line for line in prefix.splitlines()
            if line.strip() and not line.lstrip().startswith("//")
        ) + "\n"
        text += "\n// Generated x2c algorithms.\n\n"
        text += "\n".join(
            line.rstrip() for line in
            (work / f"{emitted}-generated.xlisp").read_text().splitlines()
        ) + "\n"
        text += "\n" + suffix.strip() + "\n"
    output = ROOT / f"etc/{name}.xlisp"
    if output.read_text() != text:
        output.write_text(text)
        print(f"refreshed etc/{name}.xlisp")


if __name__ == "__main__":
    main()
