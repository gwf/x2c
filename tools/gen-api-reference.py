class Fatal(Exception):
    """A condition the generator refuses to guess its way past."""


class Item:
    __slots__ = (
        "name", "receiver", "method", "signature", "line", "doc", "tier",
    )

    def __init__(self, name, signature, line, doc, tier, label="lib API"):
        self.name = name
        if "." in name:
            self.receiver, self.method = name.split(".", 1)
        else:
            # A bare function has no receiver; it groups under "Functions".
            self.receiver, self.method = "", name
        self.signature = signature
        self.line = line
        self.tier = tier
        self.doc = (
            parse_api_doc(name, line, doc, tier)
            if tier is not None
            else parse_public_doc(label, name, line, doc)
        )

    @property
    def summary(self) -> str:
        return first_sentence(self.doc)


class TypeItem:
    __slots__ = ("name", "kind", "signature", "line", "doc")

    def __init__(self, path, declaration, compiler=False):
        self.name = declaration.name
        self.kind = declaration.kind
        self.signature = declaration.signature
        self.line = declaration.line
        label = f"{path} compiler API" if compiler else f"{path} API"
        self.doc = parse_public_doc(
            label, self.name, self.line, declaration.doc
        )

    @property
    def summary(self) -> str:
        return first_sentence(self.doc)


class PathAudit:
    """Validated future-public declarations from one assigned source file."""

    __slots__ = ("path", "callables", "declarations")

    def __init__(self, path, callables, declarations):
        self.path = path
        self.callables = callables
        self.declarations = declarations


def first_sentence(doc: str) -> str:
    """Return the first sentence outside code spans and ellipses."""
    flat = " ".join(doc.split())
    code_ticks = 0
    index = 0
    while index < len(flat):
        if flat[index] == "`":
            end = index
            while end < len(flat) and flat[end] == "`":
                end += 1
            ticks = end - index
            if not code_ticks:
                code_ticks = ticks
            elif code_ticks == ticks:
                code_ticks = 0
            index = end
            continue
        if not code_ticks and flat[index] in ".!?":
            if flat[index] == "." and (
                (index and flat[index - 1] == ".")
                or (index + 1 < len(flat) and flat[index + 1] == ".")
            ):
                index += 1
                continue
            if index + 1 == len(flat) or flat[index + 1].isspace():
                return flat[:index + 1]
        index += 1
    return ""


DOC_KEYS = ("Raises", "See", "API")


def doc_sections(doc: str) -> tuple[tuple[str | None, str], ...]:
    """Split keyed sections without assigning meaning to blank lines."""
    sections: list[tuple[str | None, str]] = []
    kind: str | None = None
    lines: list[str] = []
    in_fence = False

    def flush() -> None:
        while lines and not lines[-1].strip():
            lines.pop()
        while lines and not lines[0].strip():
            lines.pop(0)
        if lines:
            sections.append((kind, "\n".join(lines)))

    for line in doc.splitlines():
        stripped = line.lstrip()
        if stripped.startswith("```"):
            in_fence = not in_fence
        key = None
        if not in_fence:
            key = next(
                (candidate for candidate in DOC_KEYS
                 if stripped.startswith(f"{candidate}:")),
                None,
            )
        if key is not None:
            flush()
            kind = key
            lines = [stripped[len(key) + 1:].lstrip()]
        else:
            lines.append(line)
    flush()
    return tuple(sections)


def parse_api_doc(
    name: str, line: int, doc: str | None, tier: str
) -> str:
    """Validate source-owned prose and ledger-owned classification."""
    doc = parse_public_doc("lib API", name, line, doc)
    for kind, _ in doc_sections(doc):
        if kind == "API":
            raise Fatal(
                f"lib API {name} at line {line} carries a source-level API "
                f"tier; classify non-primary callables in "
                f"{TIER_LEDGER.relative_to(ROOT)}"
            )
    if tier == "compatibility":
        flat = " ".join(doc.split()).lower()
        if "prefer " not in flat and "preferred" not in flat:
            raise Fatal(
                f"lib API {name} at line {line} is compatibility-tiered but "
                "does not name a preferred operation"
            )
    return doc


def parse_public_doc(
    label: str, name: str, line: int, doc: str | None
) -> str:
    """Require the minimum source-owned public documentation contract."""
    if not doc:
        raise Fatal(
            f"{label} {name} at line {line} has no doc comment; every "
            "public declaration needs prose"
        )
    if not first_sentence(doc):
        raise Fatal(
            f"{label} {name} at line {line} needs a punctuated first-sentence "
            "summary outside code spans and ellipses"
        )
    return doc


class Module:
    __slots__ = ("path", "stem", "visibility", "note", "summary", "prose",
                 "items", "declarations")

    def __init__(
        self, path, visibility, note, summary, prose, items, declarations=()
    ):
        self.path = path
        self.stem = pathlib.Path(path).stem
        self.visibility = visibility
        self.note = note
        self.summary = summary
        self.prose = prose
        self.items = items
        self.declarations = declarations


def read_manifest(*, validate_tree: bool = True
                  ) -> dict[str, tuple[str, str]]:
    rows: dict[str, tuple[str, str]] = {}
    for number, line in enumerate(
        MANIFEST.read_text(encoding="ascii").splitlines(), start=1
    ):
        if not line.strip() or line.startswith("#"):
            continue
        parts = line.split("|")
        if len(parts) != 3:
            raise Fatal(
                f"{MANIFEST.relative_to(ROOT)}:{number}: expected "
                "path|visibility|note"
            )
        path, visibility, note = (p.strip() for p in parts)
        if visibility not in VISIBILITIES:
            raise Fatal(
                f"{MANIFEST.relative_to(ROOT)}:{number}: visibility "
                f"{visibility!r} is not one of {', '.join(VISIBILITIES)}"
            )
        if path in rows:
            raise Fatal(f"{MANIFEST.relative_to(ROOT)}:{number}: duplicate "
                        f"row for {path}")
        rows[path] = (visibility, note)
    if not validate_tree:
        return rows
    present = {
        p.relative_to(ROOT).as_posix()
        for p in sorted(LIB.glob("*.x"))
        if p.name != "x2c.x"
    }
    listed = set(rows)
    for path in sorted(present - listed):
        raise Fatal(
            f"{path} is not classified in "
            f"{MANIFEST.relative_to(ROOT)}; add a row marking it "
            f"{', '.join(VISIBILITIES)}"
        )
    for path in sorted(listed - present):
        raise Fatal(
            f"{MANIFEST.relative_to(ROOT)} lists {path}, which does not exist"
        )
    return rows


def read_tier_ledger() -> dict[tuple[str, str], str]:
    """Read non-primary classifications, rejecting duplicate ownership."""
    tiers: dict[tuple[str, str], str] = {}
    for number, line in enumerate(
        TIER_LEDGER.read_text(encoding="ascii").splitlines(), start=1
    ):
        if not line.strip() or line.startswith("#"):
            continue
        parts = line.split("|")
        if len(parts) != 3:
            raise Fatal(
                f"{TIER_LEDGER.relative_to(ROOT)}:{number}: expected "
                "path|tier|comma-separated callables"
            )
        path, tier, names_text = (part.strip() for part in parts)
        if tier not in API_TIERS[1:]:
            raise Fatal(
                f"{TIER_LEDGER.relative_to(ROOT)}:{number}: tier {tier!r} "
                f"must be one of {', '.join(API_TIERS[1:])}; unlisted "
                "callables are primary"
            )
        names = [name.strip() for name in names_text.split(",")]
        if not names or any(not name for name in names):
            raise Fatal(
                f"{TIER_LEDGER.relative_to(ROOT)}:{number}: expected at "
                "least one comma-separated callable"
            )
        for name in names:
            key = (path, name)
            if key in tiers:
                raise Fatal(
                    f"{TIER_LEDGER.relative_to(ROOT)}:{number}: duplicate "
                    f"classification for {name} in {path}"
                )
            tiers[key] = tier
    return tiers


def collect() -> tuple[Module, ...]:
    """Collect every published library callable and type."""
    rows = read_manifest()
    remaining_tiers = read_tier_ledger()
    symbols = load_symbols()
    # A module's symbol table also contains the functions it forward-declares
    # for other modules -- lib/common.x declares most of the runtime. So a row
    # counts as accounted for when any lib source defines that name, not just
    # this one. The check still catches a name defined nowhere, which is what a
    # scanner gap looks like.
    defined_anywhere: set[str] = set()
    for path in sorted(rows):
        for definition in definitions_for_path(
            ROOT / path, include_static=True
        ):
            defined_anywhere.add(definition.name.replace(".", "_"))
    modules: list[Module] = []
    for path in sorted(rows):
        visibility, note = rows[path]
        source = ROOT / path
        text = source.read_text(encoding="utf-8")
        summary = module_summary(text, source)
        if summary.startswith("Current source module"):
            raise Fatal(
                f"{path} has no module comment to summarize; add a "
                "`/*  <file>.x -- <summary>` header"
            )
        items: list[Item] = []
        declarations: list[TypeItem] = []
        if visibility in ("api", "optional"):
            audit = _collect_public_surface(
                source, path, symbols, compiler=False, check_hash=True,
                root=ROOT
            )
            for definition in audit.callables:
                key = (path, definition.name)
                tier = remaining_tiers.pop(key, "primary")
                items.append(Item(
                    definition.name, definition.signature, definition.line,
                    definition.doc, tier
                ))
            declarations.extend(
                TypeItem(path, declaration)
                for declaration in audit.declarations
            )
            # A row whose name no lib source defines is a prototype that
            # would fail at link. Not fatal -- removing one rewrites the
            # tracked symbol snapshot, which is maintainer-gated -- but it
            # gets published so it cannot hide.
            table = symbols.functions(path)
            DANGLING.update(
                (orphan, path)
                for orphan in unmatched(path, table, items, defined_anywhere)
            )
        else:
            for definition in definitions_for_path(source):
                # Contract and internal modules have no generated callable
                # surface, so public-looking prose here would be dropped.
                if definition.doc:
                    raise Fatal(
                        f"{path}:{definition.line}: {definition.name} carries "
                        f"a doc comment but {path} is marked {visibility}"
                    )
        modules.append(Module(
            path, visibility, note, summary, module_prose(text), tuple(items),
            tuple(declarations)
        ))
    if remaining_tiers:
        path, name = sorted(remaining_tiers)[0]
        raise Fatal(
            f"{TIER_LEDGER.relative_to(ROOT)} classifies {name} in {path}, "
            "but that name is not a published callable in that module"
        )
    for module in modules:
        if any(item.tier == "primary" for item in module.items):
            if module.stem not in PRIMARY_EVIDENCE:
                raise Fatal(
                    f"{module.path} has primary API but no executable "
                    "evidence mapping"
                )
    return tuple(modules)


def collect_compiler(*, symbols=None, root: pathlib.Path = ROOT
                     ) -> tuple[Module, ...]:
    """Collect every future-public compiler callable and type."""
    symbols = load_symbols() if symbols is None else symbols
    modules = []
    for source in sorted((root / "src").glob("*.x")):
        path = source.relative_to(root).as_posix()
        text = source.read_text(encoding="utf-8")
        summary = module_summary(text, source)
        if summary.startswith("Current source module"):
            raise Fatal(
                f"{path} has no module comment to summarize; add a "
                "`/*  <file>.x -- <summary>` header"
            )
        audit = _collect_public_surface(
            source, path, symbols, compiler=True, check_hash=True,
            root=root
        )
        label = f"{path} compiler API"
        items = tuple(
            Item(
                definition.name, definition.signature, definition.line,
                definition.doc, None, label
            )
            for definition in audit.callables
        )
        declarations = tuple(
            TypeItem(path, declaration, compiler=True)
            for declaration in audit.declarations
        )
        modules.append(Module(
            path, "compiler", "", summary, module_prose(text), items,
            declarations
        ))
    return tuple(modules)


def content_check(path: str, symbols, *, root: pathlib.Path = ROOT) -> None:
    from x2c_symbols import content_hash
    actual = content_hash((root / path).read_bytes())
    if actual != symbols.file_hash(path):
        raise Fatal(
            f"{path}: etc/header-symbols.xlisp is stale for this file "
            f"({actual} != {symbols.file_hash(path)}); run "
            "'make hdr-sync'"
        )


def verify(path: str, definition, entry) -> None:
    ret, _, params = split_signature(definition.signature)
    owner = definition.name.split(".", 1)[0]
    ret = re.sub(r"\bSelf\b", owner, ret)
    params = tuple(re.sub(r"\bSelf\b", owner, param) for param in params)
    source_params = tuple(
        p for p in (_strip_param_name(p) for p in params) if p
    )
    where = f"{path}:{definition.line}: {definition.name}"
    if len(source_params) != len(entry.params):
        raise Fatal(f"{where} takes {len(source_params)} parameters, the "
                    f"symbol table says {len(entry.params)}")
    if _unqualified(ret) != _unqualified(entry.returns):
        raise Fatal(f"{where} returns {ret!r}, the symbol table says "
                    f"{entry.returns!r}")
    for source_type, artifact_type in zip(source_params, entry.params):
        if normalize_type(source_type) != normalize_type(artifact_type):
            raise Fatal(f"{where} has parameter {source_type!r}, the symbol "
                        f"table says {artifact_type!r}")


def _future_public_name(name: str) -> bool:
    """Whether a non-static source name belongs to the future public API."""
    return not name.startswith("_") and "__" not in name


def _source_path(path: str | pathlib.Path, root: pathlib.Path
                 ) -> tuple[pathlib.Path, str, str]:
    """Resolve one check path and identify its compiler or library area."""
    candidate = pathlib.Path(path)
    if not candidate.is_absolute():
        candidate = root / candidate
    candidate = candidate.resolve()
    try:
        relative = candidate.relative_to(root.resolve()).as_posix()
    except ValueError as exc:
        raise Fatal(f"{path}: path is outside {root}") from exc
    parts = pathlib.PurePosixPath(relative).parts
    if len(parts) != 2 or parts[0] not in ("src", "lib") \
            or candidate.suffix != ".x":
        raise Fatal(
            f"{relative}: expected one hand-authored src/*.x or lib/*.x file"
        )
    if not candidate.is_file() or candidate.name == "x2c.x":
        raise Fatal(f"{relative}: source file does not exist or is generated")
    return candidate, relative, parts[0]


def _artifact_tables(symbols, path: str):
    """Return artifact rows with a useful missing-path error."""
    try:
        return symbols.functions(path), symbols.rows(path)
    except KeyError as exc:
        raise Fatal(
            f"{path}: absent from etc/header-symbols.xlisp; run "
            "'make hdr-sync'"
        ) from exc


def verify_declaration(path: str, declaration, rows) -> None:
    """Require a source declaration name to exist in the compiler artifact."""
    if declaration.name not in rows:
        raise Fatal(
            f"{path}:{declaration.line}: {declaration.name} is absent from "
            "etc/header-symbols.xlisp; run 'make hdr-sync'"
        )


def _collect_public_surface(
    source: pathlib.Path, relative: str, symbols, *, compiler: bool,
    check_hash: bool, root: pathlib.Path = ROOT,
) -> PathAudit:
    """Validate one complete compiler or published-library surface."""
    if check_hash:
        content_check(relative, symbols, root=root)
    function_rows, declaration_rows = _artifact_tables(symbols, relative)
    label = f"{relative} compiler API" if compiler else f"{relative} API"
    callables = []
    for definition in definitions_for_path(source):
        if not _future_public_name(definition.name):
            if definition.doc:
                raise Fatal(
                    f"{relative}:{definition.line}: {definition.name} "
                    "carries a doc comment but is excluded from the public "
                    "API"
                )
            continue
        artifact_name = definition.name.replace(".", "_")
        entry = function_rows.get(artifact_name)
        if entry is None:
            raise Fatal(
                f"{relative}:{definition.line}: {definition.name} is absent "
                "from etc/header-symbols.xlisp; run 'make hdr-sync'"
            )
        verify(relative, definition, entry)
        parse_public_doc(label, definition.name, definition.line,
                         definition.doc)
        callables.append(definition)

    declarations = []
    for declaration in public_declarations_for_path(source):
        if not _future_public_name(declaration.name):
            if declaration.doc:
                raise Fatal(
                    f"{relative}:{declaration.line}: {declaration.name} "
                    "carries a doc comment but is excluded from the public "
                    "API"
                )
            continue
        verify_declaration(relative, declaration, declaration_rows)
        parse_public_doc(label, declaration.name, declaration.line,
                         declaration.doc)
        declarations.append(declaration)

    return PathAudit(relative, tuple(callables), tuple(declarations))


def collect_public_path(
    path: str | pathlib.Path, *, manifest=None, symbols=None,
    root: pathlib.Path = ROOT,
) -> PathAudit:
    """Collect and validate one future-public compiler or library surface.

    Unlike normal generated-reference collection, this deliberately ignores
    the artifact's content hash. Writers run it after comment-only edits and
    before the integrator refreshes the artifact. Names and signatures still
    have to agree with the artifact, so signature drift cannot hide behind
    that allowance.
    """
    source, relative, area = _source_path(path, root)
    if area == "src":
        compiler = True
    else:
        manifest = (
            read_manifest(validate_tree=False) if manifest is None
            else manifest
        )
        if relative not in manifest:
            raise Fatal(f"{relative}: not classified in the library manifest")
        visibility, _ = manifest[relative]
        if visibility not in ("api", "optional"):
            raise Fatal(
                f"{relative}: {visibility} library modules do not publish a "
                "callable or type surface"
            )
        compiler = False

    symbols = load_symbols() if symbols is None else symbols
    return _collect_public_surface(
        source, relative, symbols, compiler=compiler, check_hash=False,
        root=root
    )


def collect_public_paths(paths, *, manifest=None, symbols=None,
                         root: pathlib.Path = ROOT
                         ) -> tuple[PathAudit, ...]:
    """Collect multiple non-overlapping writer paths in argument order."""
    paths = tuple(paths)
    symbols = load_symbols() if symbols is None else symbols
    if manifest is None:
        areas = {_source_path(path, root)[2] for path in paths}
        manifest = (
            read_manifest(validate_tree=False) if "lib" in areas else {}
        )
    return tuple(
        collect_public_path(
            path, manifest=manifest, symbols=symbols, root=root
        )
        for path in paths
    )


def unmatched(path: str, table, items, accounted: set[str]) -> set[str]:
    """Func rows whose receiver we documented but whose name we never saw.

    `accounted` includes static definitions, so a static method is not
    mistaken for a scanner gap.
    """
    found = {item.name.replace(".", "_") for item in items}
    receivers = {item.receiver for item in items}
    missing = set()
    for name in table:
        if name in found or name in accounted:
            continue
        if name.startswith("_"):
            continue
        if "_" not in name:
            continue
        receiver = name.split("_", 1)[0]
        if receiver in receivers:
            missing.add(name)
    return missing


def anchor(name: str) -> str:
    return name


PLAIN_HEADING_ID = re.compile(r"[a-z0-9_-]+\Z")


def render_api_heading(name: str, level: int) -> list[str]:
    """Render one API heading with a stable raw-name fragment."""
    heading = f"{'#' * level} {name}"
    if PLAIN_HEADING_ID.fullmatch(name):
        return [heading]
    return [f'<a id="{anchor(name)}"></a>', heading]


def render_doc(module: Module, item: Item) -> list[str]:
    """Render a doc comment, promoting recognized keyed sections."""
    out: list[str] = []
    for kind, section in doc_sections(item.doc):
        flat = " ".join(section.split())
        if kind == "Raises":
            lines = section.splitlines()
            lines[0] = f"**Raises:** {lines[0]}"
            out.extend(("\n".join(lines), ""))
            continue
        if kind == "See":
            targets = [
                target.strip() for target in flat.split(",")
                if target.strip()
            ]
            linked = "**See:** " + ", ".join(
                see_link(module, item, target) for target in targets
            )
            out.extend(("\n".join(textwrap.wrap(linked, width=79)), ""))
            continue
        out.extend((section, ""))
    return out


def see_link(module: Module, item: Item, target: str) -> str:
    """Resolve one See: entry, or fail.

    check_links() in tools/check-docs.py strips a fragment before resolving, so
    a wrong method name inside a page would pass unnoticed. This is the only
    place that can catch it.
    """
    if target.endswith(".md") or "/" in target:
        destination = (PAGES / target).resolve()
        if not destination.exists():
            raise Fatal(
                f"{module.path}:{item.line}: {item.name} has 'See: {target}', "
                f"which does not resolve to a page"
            )
        return f"[{pathlib.Path(target).stem}]({target})"
    if "." not in target:
        raise Fatal(
            f"{module.path}:{item.line}: {item.name} has 'See: {target}'; "
            "expected a Type.method reference or a page path"
        )
    if target not in SEE_INDEX:
        raise Fatal(
            f"{module.path}:{item.line}: {item.name} has 'See: {target}', "
            "which is not a documented public function"
        )
    where = SEE_INDEX[target]
    if where == module.stem:
        return f"[`{target}`](#{anchor(target)})"
    return f"[`{target}`]({where}.md#{anchor(target)})"


