def render_types(module: Module) -> list[str]:
    """Render one module's public type table and declarations."""
    if not module.declarations:
        return []
    lines = [
        "## Public types",
        "",
        "| Type | Kind | Summary |",
        "| --- | --- | --- |",
    ]
    for item in sorted(module.declarations, key=lambda value: value.name):
        lines.append(
            f"| [`{item.name}`](#{anchor(item.name)}) | {item.kind} | "
            f"{item.summary} |"
        )
    lines.append("")
    for item in sorted(module.declarations, key=lambda value: value.name):
        lines.extend(render_api_heading(item.name, 3))
        lines.extend((
            "",
            f"`{item.signature}`",
            "",
        ))
        lines.extend(render_doc(module, item))
        lines.extend((f"Source: `{module.path}:{item.line}`", ""))
    return lines


def render_page(module: Module) -> str:
    lead = module.summary[:1].upper() + module.summary[1:]
    lines = [BANNER, "", f"# `{module.path}`", "", lead, ""]
    if module.items:
        for tier in API_TIERS:
            tier_items = [item for item in module.items if item.tier == tier]
            if not tier_items:
                continue
            lines.extend((
                f"## {TIER_HEADINGS[tier]}",
                "",
            ))
            if tier == "internal":
                lines.extend((
                    "These callables connect runtime translation units. They "
                    "are documented",
                    "for source readers but are not supported as user API.",
                    "",
                ))
            lines.extend((
                "| Function | Summary |",
                "| --- | --- |",
            ))
            for item in sorted(
                tier_items, key=lambda i: (i.receiver, i.method)
            ):
                lines.append(
                    f"| [`{item.name}`](#{anchor(item.name)}) | "
                    f"{item.summary} |"
                )
            lines.append("")
            receivers: dict[str, list[Item]] = {}
            for item in tier_items:
                receivers.setdefault(item.receiver, []).append(item)
            for receiver in sorted(receivers):
                heading = f"### `{receiver}`" if receiver else "### Functions"
                lines.extend((heading, ""))
                for item in sorted(
                    receivers[receiver], key=lambda i: i.method
                ):
                    lines.extend(render_api_heading(item.name, 4))
                    lines.extend((
                        "",
                        f"`{item.signature}`",
                        "",
                    ))
                    lines.extend(render_doc(module, item))
                    lines.extend((
                        f"Source: `{module.path}:{item.line}`",
                        "",
                    ))
    lines.extend(render_types(module))
    if module.prose:
        lines.extend(("## Design notes", ""))
        for paragraph in module.prose:
            lines.extend((paragraph, ""))
    if any(item.tier == "primary" for item in module.items):
        lines.extend((
            "## Tests and examples", "", PRIMARY_EVIDENCE[module.stem], "",
        ))
    return "\n".join(lines).rstrip() + "\n"


