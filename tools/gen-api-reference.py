def render_index(modules: tuple[Module, ...]) -> str:
    contract = [m for m in modules if m.visibility == "contract"]
    optional = [m for m in modules if m.visibility == "optional"]
    internal = [m for m in modules if m.visibility == "internal"]
    published = [
        module for module in modules
        if module.visibility in ("api", "optional")
    ]
    lines = [
        BANNER,
        "",
        "# Module Reference",
        "",
        "Reference pages list the functions and types in each runtime module.",
        "Start with the [standard library overview](../overview.md) to choose",
        "a type or find a function for a particular task.",
        "",
        "The [x2c C API](x2c-c-api.md) collects the stable `x2c_*` entry",
        "points used by generated code, native callers, and compiler setup.",
        "",
        "## Modules",
        "",
        "| Module | Description |",
        "| --- | --- |",
    ]
    for module in published:
        lines.append(
            f"| [`{module.path}`]({module.stem}.md) | {module.summary} |"
        )
    def add_module_section(
        group: list[Module], heading: str, *intro: str
    ) -> None:
        if not group:
            return
        lines.extend(("", heading, "", *intro, ""))
        for module in group:
            lines.append(
                f"- `{module.path}` - {module.note or module.summary}"
            )

    add_module_section(
        contract,
        "## Described by the overview",
        "These modules provide shared types and declarations. See the",
        "[standard library overview](../overview.md) for their use.",
    )
    if optional:
        lines.extend((
            "",
            "## Optional x2c modules",
            "",
            "These modules ship with x2c but are not loaded by the standard",
            "prelude. Include one explicitly to use its declarations.",
            "",
        ))
        for module in optional:
            lines.append(
                f"- [`{module.path}`]({module.stem}.md) - "
                f"{module.note or module.summary}"
            )
    add_module_section(
        internal,
        "## Runtime-internal",
        "These modules implement the runtime and are not public APIs.",
    )
    if DANGLING:
        lines.extend((
            "",
            "## Declared but not defined",
            "",
            "These prototypes reach the generated headers, but no runtime",
            "source defines them. Calling one fails at link time.",
            "",
        ))
        for name in sorted(DANGLING):
            lines.append(
                f"- `{name.replace('_', '.', 1)}` - declared in "
                f"`{DANGLING[name]}`"
            )
    return "\n".join(lines).rstrip() + "\n"


