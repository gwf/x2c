"""Generate the library and provisional compiler API reference pages.

Signatures come from `etc/header-symbols.xlisp`, the compiler's own tracked
symbol table, prose comes from `/**` doc comments in `src/*.x` and `lib/*.x`,
and non-primary library API tiers come from `docs/library-api-tiers.txt`.
Every signature is cross-checked against the compiler artifact, so a page
cannot claim a function shape the compiler disagrees with.

This tool owns `docs/src/library/modules/`,
`docs/src/internals/compiler-api/`, and their sections of
`docs/src/SUMMARY.md`. It does not touch `docs/src/library/overview.md`,
which is authored prose.

`--check-path` audits one or more assigned compiler or library sources without
changing the currently generated book surface. It ignores only the artifact's
file-content hash so comment writers can check their work before `hdr-sync`;
names and callable signatures must still match the compiler artifact.

    python3 tools/gen-api-reference.py --write
    python3 tools/gen-api-reference.py --check
    python3 tools/gen-api-reference.py --check-path src/compiler.x
"""

