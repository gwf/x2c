def render_x2c_api(modules: tuple[Module, ...]) -> str:
    rows = []
    for module in modules:
        for item in module.items:
            if item.name.startswith("x2c_"):
                rows.append((module.path, module.stem, item))
    for definition in definitions_for_path(COMPILER_X2C_SOURCE):
        if not definition.name.startswith("x2c_"):
            continue
        if not definition.doc:
            raise Fatal(
                f"{COMPILER_X2C_SOURCE.relative_to(ROOT)}:{definition.line}: "
                f"{definition.name} has no doc comment"
            )
        rows.append(("src/utils.x", "", Item(
            definition.name, definition.signature, definition.line,
            definition.doc, "advanced"
        )))
    lines = [
        MIXED_BANNER,
        "",
        "# x2c C API",
        "",
        "The `x2c_*` prefix is reserved for stable C entry points used by",
        "generated code, native callers, or process-wide compiler setup.",
        "Typed operations use methods such as `Atom.promote`",
        "and `Lisp.program`; their generated C spellings are not part of this",
        "prefix.",
        "",
        "| Function | Source | Signature |",
        "| --- | --- | --- |",
    ]
    for path, stem, item in sorted(rows, key=lambda row: row[2].name):
        function = f"`{item.name}`"
        if stem:
            function = f"[`{item.name}`]({stem}.md#{anchor(item.name)})"
        lines.append(
            f"| {function} | `{path}` | `{item.signature}` |"
        )
    lines.extend((
        "",
        f"Total: {len(rows)} functions.",
        "",
    ))
    return "\n".join(lines)


def _replace_summary_section(
    current: str, heading: str, section: list[str], *,
    before: str | None = None,
) -> str:
    """Replace one generated section or insert it before a stable heading."""
    lines = current.split("\n")
    if heading in lines:
        start = lines.index(heading)
        end = start + 1
        while end < len(lines) and not lines[end].startswith("# "):
            end += 1
        return "\n".join(lines[:start] + section + lines[end:])
    if before is None or before not in lines:
        destination = f" before {before!r}" if before else ""
        raise Fatal(
            f"{SUMMARY.relative_to(ROOT)} has no {heading!r} heading and no "
            f"stable insertion point{destination}"
        )
    start = lines.index(before)
    return "\n".join(lines[:start] + section + lines[start:])


def render_summary(
    modules: tuple[Module, ...], compiler: tuple[Module, ...], current: str
) -> str:
    standard = [
        SECTION,
        "",
        "- [Standard Library Overview](library/overview.md)",
        "- [Module Reference](library/modules/index.md)",
        "  - [x2c C API](library/modules/x2c-c-api.md)",
    ]
    for module in modules:
        if module.visibility not in ("api", "optional"):
            continue
        standard.append(
            f"  - [{module.path}](library/modules/{module.stem}.md)"
        )
    standard.append("")
    updated = _replace_summary_section(current, SECTION, standard)
    compiler_section = [
        COMPILER_SECTION,
        "",
        "- [Compiler API (provisional)](internals/compiler-api/index.md)",
    ]
    for module in compiler:
        compiler_section.append(
            f"  - [{module.path}](internals/compiler-api/{module.stem}.md)"
        )
    compiler_section.append("")
    return _replace_summary_section(
        updated, COMPILER_SECTION, compiler_section, before=INTERNALS_SECTION
    )


def build() -> tuple[dict[pathlib.Path, str], str]:
    DANGLING.clear()
    modules = collect()
    compiler = collect_compiler()
    SEE_INDEX.clear()
    for module in modules:
        if module.visibility not in ("api", "optional"):
            continue
        for item in module.items:
            SEE_INDEX[item.name] = module.stem
    pages: dict[pathlib.Path, str] = {
        PAGES / "index.md": render_index(modules),
        PAGES / "x2c-c-api.md": render_x2c_api(modules),
        COMPILER_PAGES / "index.md": render_compiler_index(compiler),
    }
    for module in modules:
        if module.visibility in ("api", "optional"):
            pages[PAGES / f"{module.stem}.md"] = render_page(module)
    for module in compiler:
        pages[COMPILER_PAGES / f"{module.stem}.md"] = \
            render_compiler_page(module)
    summary = render_summary(
        modules, compiler, SUMMARY.read_text(encoding="utf-8")
    )
    return pages, summary


def write(pages: dict[pathlib.Path, str], summary: str) -> int:
    for path, text in sorted(pages.items()):
        path.parent.mkdir(parents=True, exist_ok=True)
        temporary = path.with_suffix(".md.tmp")
        temporary.write_text(text, encoding="ascii")
        os.replace(temporary, path)
    for directory in (PAGES, COMPILER_PAGES):
        if directory.exists():
            for existing in sorted(directory.glob("*.md")):
                if existing not in pages:
                    existing.unlink()
    SUMMARY.write_text(summary, encoding="utf-8")
    print(f"wrote {len(pages)} API pages and updated "
          f"{SUMMARY.relative_to(ROOT)}")
    return 0


def check(pages: dict[pathlib.Path, str], summary: str) -> int:
    problems: list[str] = []
    for path, text in sorted(pages.items()):
        actual = path.read_text(encoding="ascii") if path.exists() else ""
        if actual != text:
            problems.append("\n".join(difflib.unified_diff(
                actual.splitlines(), text.splitlines(),
                fromfile=str(path.relative_to(ROOT)), tofile="generated",
                lineterm="",
            )))
    for directory in (PAGES, COMPILER_PAGES):
        if directory.exists():
            for existing in sorted(directory.glob("*.md")):
                if existing not in pages:
                    problems.append(
                        f"{existing.relative_to(ROOT)}: page is no longer "
                        "generated and should be removed"
                    )
    if SUMMARY.read_text(encoding="utf-8") != summary:
        problems.append("\n".join(difflib.unified_diff(
            SUMMARY.read_text(encoding="utf-8").splitlines(),
            summary.splitlines(),
            fromfile=str(SUMMARY.relative_to(ROOT)), tofile="generated",
            lineterm="",
        )))
    if problems:
        for problem in problems:
            print(problem, file=sys.stderr)
        print("run 'make doc-generate' and review the API reference diff",
              file=sys.stderr)
        return 1
    print(f"API reference is current ({len(pages)} pages)")
    return 0


def check_paths(paths) -> int:
    """Check assigned source paths without generating or checking pages."""
    audits = collect_public_paths(paths)
    callables = sum(len(audit.callables) for audit in audits)
    declarations = sum(len(audit.declarations) for audit in audits)
    print(
        f"public documentation is complete for {len(audits)} paths "
        f"({callables} callables, {declarations} types)"
    )
    return 0


def main() -> int:
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    mode.add_argument(
        "--check-path", action="append", metavar="PATH",
        help="check one future-public source path; may be repeated",
    )
    args = parser.parse_args()
    if args.check_path:
        try:
            return check_paths(args.check_path)
        except Fatal as error:
            print(f"source documentation: {error}", file=sys.stderr)
            return 1
    try:
        pages, summary = build()
    except Fatal as error:
        print(f"API reference: {error}", file=sys.stderr)
        return 1
    if args.write:
        return write(pages, summary)
    if args.check:
        return check(pages, summary)
    for path in sorted(pages):
        print(f"--- {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
