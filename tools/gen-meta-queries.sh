#!/bin/sh
# Writes etc/meta-queries.x, the project meta helper's forwarders for the
# compiler operations. A public `meta` function in lib/meta.x has no run-time
# form when it is a bodyless prototype or reaches one; each such function
# that etc/meta-helper.x does not define itself becomes a function that asks
# the compiler. The file is rewritten only when its text changes.
set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
out=${1:-$root/etc/meta-queries.x}
cd "$root"

tmp="$out.$$"
trap 'rm -f "$tmp"' EXIT
awk '
function name_of(text,    name) {
  name = text
  sub(/\(.*/, "", name)
  sub(/.*[ \t*]/, "", name)
  return name
}
function finish(    signature) {
  open = 0
  signature = substr(text, 6)
  sub(/[ \t\n]*(=>|\{).*/, "", signature)
  sub(/;[ \t]*$/, "", signature)
  signatures[++count] = signature
  names[count] = name_of(signature)
  reaches[count] = text ~ /\);[ \t]*$/ && text !~ /=>/
  statics[count] = text ~ /^meta static /
  bodies[count] = text
}
FILENAME == "etc/meta-helper.x" {
  if ($0 ~ /^[A-Za-z].*\(/) local[name_of($0)] = 1
  next
}
/^meta / { text = $0; open = 1; depth = 0 }
open && text != $0 { text = text "\n" $0 }
open {
  depth += gsub(/\{/, "{") - gsub(/\}/, "}")
  if (depth == 0 && $0 ~ /(;|\})[ \t]*$/) finish()
}
END {
  do {
    changed = 0
    for (i = 1; i <= count; i++) {
      if (reaches[i]) continue
      for (j = 1; j <= count; j++) {
        callee = names[j]
        sub(/.*\./, "", callee)
        if (reaches[j] &&
            bodies[i] ~ ("(^|[^A-Za-z0-9_])" callee "[ \t]*\\(")) {
          reaches[i] = changed = 1
          break
        }
      }
    }
  } while (changed)
  print "/*  meta-queries.x -- the compiler operations a project meta helper asks"
  print ""
  print "    Generated by tools/gen-meta-queries.sh; do not edit. Each public"
  print "    `meta` function in lib/meta.x without a run-time form that"
  print "    etc/meta-helper.x does not define asks the compiler, which applies"
  print "    its own operation. The helper compiles this file after"
  print "    etc/meta-helper.x, as one unit."
  print "*/"
  print ""
  for (i = 1; i <= count; i++) {
    if (!reaches[i] || statics[i] || names[i] in local) continue
    signature = signatures[i]
    one = signature
    gsub(/\n */, " ", one)
    sub(/\( /, "(", one)
    parameters = one
    sub(/^[^(]*\(/, "", parameters)
    sub(/\)$/, "", parameters)
    arguments = ""
    if (parameters != "void") {
      n = split(parameters, parts, ",")
      for (p = 1; p <= n; p++)
        arguments = arguments (p > 1 ? " " : "") "$" name_of(parts[p] "(")
    }
    target = names[i]
    sub(/\./, "_", target)
    ask = "_ask(\"" target "\", %(" arguments "))"
    if (signature ~ /^void /) print signature " { " ask "; }"
    else if (length(one " => " ask ";") <= 79) print one " => " ask ";"
    else print signature " =>\n  " ask ";"
  }
}
' etc/meta-helper.x lib/meta.x > "$tmp"
if [ -e "$out" ] && cmp -s "$tmp" "$out"; then
  rm -f "$tmp"
else
  mv "$tmp" "$out"
fi
trap - EXIT
